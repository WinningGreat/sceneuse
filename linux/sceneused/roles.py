def normalize_role(raw: str | None) -> str:
    if not raw:
        return "unknown"
    key = raw.strip().lower().replace("-", "_").replace(" ", "_")
    if key.startswith("role_"):
        key = key[5:]
    return _ROLE.get(key, key)


def normalize_action(raw: str | None) -> str:
    if not raw:
        return "press"
    key = raw.strip().lower()
    return _ACTION.get(key, key.replace(" ", "_"))


